export function getTechIcon(name: string, className = "w-4 h-4") {
  const lower = name.toLowerCase();
  if (lower.includes("python")) return <PythonIcon className={className} />;
  if (lower.includes("power bi")) return <PowerBiIcon className={className} />;
  if (lower.includes("sql") || lower.includes("mysql") || lower.includes("data modeling")) return <SqlIcon className={className} />;
  if (lower.includes("scikit") || lower.includes("machine learning") || lower.includes("regression")) return <ScikitLearnIcon className={className} />;
  if (lower.includes("pandas") || lower.includes("numpy")) return <PandasIcon className={className} />;
  if (lower.includes("tableau")) return <TableauIcon className={className} />;
  if (lower.includes("excel")) return <ExcelIcon className={className} />;
  if (lower.includes("nlp") || lower.includes("nltk") || lower.includes("vectorization")) return <NlpIcon className={className} />;
  return <DefaultTechIcon className={className} />;
}

